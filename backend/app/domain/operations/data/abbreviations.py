_BY_KEY: dict[str, str] = {}
for _key, _value in ABBREVIATIONS:
    _BY_KEY.setdefault(_key.casefold(), _value)


def lookup_abbreviation(token: str) -> str:
    """Return the printed expansion of a token, or an empty string."""
    return _BY_KEY.get((token or "").strip().casefold(), "")
